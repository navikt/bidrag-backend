CREATE TABLE IF NOT EXISTS sak
(
    id                  BIGINT    NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    saksnummer          TEXT      NOT NULL,
    eierfogd            TEXT      NOT NULL,
    opprettet_tidspunkt TIMESTAMP NOT NULL DEFAULT now(),
    endret_tidspunkt    TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT unik_sak_saksnummer UNIQUE (saksnummer)
);

