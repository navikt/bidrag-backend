CREATE TABLE IF NOT EXISTS valutakursgrunnlag
(
    valutakursgrunnlag_id integer NOT NULL GENERATED BY DEFAULT AS IDENTITY ( INCREMENT 1 START 1 MINVALUE 1 MAXVALUE 2147483647 CACHE 1 ),
    bruk_fra timestamp NOT NULL,
    bruk_til timestamp NOT NULL,
    hentet_tidspunkt timestamp DEFAULT now() NOT NULL,
    oppdatert_tidspunkt timestamp DEFAULT now() NOT NULL,
    kurs numeric(38, 16),
    multiplikator integer,
    basisvaluta varchar(3) NOT NULL,
    kvoteringsvaluta varchar(3) NOT NULL,
    feilet_henting boolean DEFAULT false NOT NULL,
    status varchar(10) NOT NULL,
    kilde varchar(20),
    observasjonsdato date,
    CONSTRAINT valutakursgrunnlag_pkey PRIMARY KEY (valutakursgrunnlag_id),
    CONSTRAINT valutakursgrunnlag_periode_unique UNIQUE (basisvaluta, bruk_fra)
)
    TABLESPACE pg_default;